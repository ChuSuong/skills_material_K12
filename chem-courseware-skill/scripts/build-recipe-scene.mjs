function jsString(value) {
  return JSON.stringify(String(value ?? ''));
}

function jsLiteral(value) {
  return JSON.stringify(value, null, 2);
}

function parseAnchorRef(value, fallbackApparatus, fallbackAnchor) {
  const [apparatus, anchor] = String(value || `${fallbackApparatus}.${fallbackAnchor}`).split('.');
  return {
    apparatus: apparatus || fallbackApparatus,
    anchor: anchor || fallbackAnchor,
  };
}

function findRecipeStep(recipe, type, fallbackId) {
  return recipe.steps?.find((step) => step.id === fallbackId)
    || recipe.steps?.find((step) => step.type === type)
    || null;
}

