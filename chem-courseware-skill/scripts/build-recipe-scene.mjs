export function supportsRecipeSceneBuilder(recipeId) {
  return supportedRecipeIds.has(recipeId);
}

export function buildRecipeSceneArtifact({ draft, recipe } = {}) {
  if (!recipe?.id) {
    throw new Error('recipe.id is required');
  }
  if (!supportsRecipeSceneBuilder(recipe.id)) {
    throw new Error(`Recipe scene builder does not support recipe: ${recipe.id}`);
  }

  return {
    hudSource: buildExperimentHud({ draft, recipe }),
    sceneSource: recipe.id === 'ch4-combustion-flame-test'
      ? buildCh4CombustionScene({ draft, recipe })
      : buildIronCuso4Scene({ draft, recipe }),
    generatedBy: 'recipe-scene-builder',
  };
}
