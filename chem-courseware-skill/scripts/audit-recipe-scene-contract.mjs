import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { validateRecipeDefinition } from '../lib/contracts/recipe.js';
import { isActiveClassicRecipeId } from './classic-kit-active-config.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const recipesDir = path.join(repoRoot, 'recipes');

const effectPatterns = {
  'pour-stream': /\b(stream|pourStream)\b[\s\S]{0,120}\bnew\s+THREE\.Mesh\s*\(/i,
  'bubble-field': /\b(bubble|bubbles|bubbleField)\b[\s\S]{0,160}\bnew\s+THREE\.(Mesh|SphereGeometry|Points)\b/i,
  'steam-field': /\b(steam|smoke|steamField)\b[\s\S]{0,160}\bnew\s+THREE\.(Mesh|Points)\b/i,
  'spark-field': /\b(spark|sparkField)\b[\s\S]{0,160}\bnew\s+THREE\.(Mesh|Points)\b/i,
  'glow-ring': /\b(glow|glowRing)\b[\s\S]{0,160}\bnew\s+THREE\.(Mesh|TorusGeometry|RingGeometry)\b/i,
  'flame-plume': /\b(flame|flamePlume)\b[\s\S]{0,160}\bnew\s+THREE\.(Mesh|ConeGeometry|ShaderMaterial|MeshBasicMaterial)\b/i,
  'color-transition': /\.material\.color\.(copy|lerp|lerpColors|setHSL)\s*\(/,
};

const generatedSceneLocalThreePattern = /\bnew\s+THREE\.(Mesh|Points|Line|BoxGeometry|CylinderGeometry|SphereGeometry|ConeGeometry|TorusGeometry|RingGeometry|CircleGeometry|PlaneGeometry|BufferGeometry|MeshStandardMaterial|MeshBasicMaterial|MeshPhysicalMaterial|ShaderMaterial|PointsMaterial)\b/;
const dragStepTypes = new Set(['drag-drop-anchor', 'drag-pour-anchor', 'drag-heat-anchor']);

async function loadRecipe(recipeId) {
  const recipePath = path.join(recipesDir, `${recipeId}.recipe.json`);
  const raw = await fs.readFile(recipePath, 'utf8');
  const result = validateRecipeDefinition(JSON.parse(raw));
  if (!result.ok) {
    throw new Error(`Invalid recipe ${recipeId}: ${result.errors.join(', ')}`);
  }
  return result.recipe;
}

export async function auditRecipeSceneContract({ draft, sceneSource, recipe = null } = {}) {
  const errors = [];
  const warnings = [];
  const recipeId = draft?.recipe || recipe?.id;

  if (!recipeId) {
    return { ok: true, errors, warnings };
  }

  const resolvedRecipe = recipe || await loadRecipe(recipeId);
  const generatedByRecipeBuilder = /@generated by scripts\/build-recipe-scene\.mjs/.test(sceneSource);

  if (/free-drag/.test(resolvedRecipe.interaction || '')) {
    if (!/\bcreateFreeDragController\s*\(/.test(sceneSource)) {
      errors.push('recipe scene must use createFreeDragController() for free-drag interactions');
    }
    if (resolvedRecipe.steps?.some((step) => dragStepTypes.has(step.type)) && !/\.registerDraggable\s*\(/.test(sceneSource)) {
      errors.push('recipe scene with drag steps must register at least one draggable');
    }
    for (const step of resolvedRecipe.steps || []) {
      if (!dragStepTypes.has(step?.type)) {
        continue;
      }
      if (!Number.isFinite(step.overlapPadding)) {
        errors.push(`free-drag recipe step must declare overlapPadding: ${step.id || step.type}`);
      }
    }
    if (/addEventListener\s*\(\s*['"]pointer(down|move|up|cancel)['"]/.test(sceneSource)) {
      errors.push('recipe scene must not implement scene-local pointer drag listeners');
    }
  }

  if (generatedByRecipeBuilder) {
    if (!/\bgetCapabilities\s*\(\)\s*\{/.test(sceneSource)) {
      errors.push('generated recipe scene must expose getCapabilities() through the courseware test harness');
    }
    if (!/\bgetStepContract\s*\(\)\s*\{/.test(sceneSource)) {
      errors.push('generated recipe scene must expose getStepContract() through the courseware test harness');
    }
    if (!/\brecipeStepContract\b/.test(sceneSource)) {
      errors.push('generated recipe scene must embed recipeStepContract');
    }
    if (!/\brecipeCapabilities\b/.test(sceneSource)) {
      errors.push('generated recipe scene must embed recipeCapabilities');
    }
    if (!/\bresultSustainEffects\b/.test(sceneSource)) {
      errors.push('generated recipe scene must expose resultSustainEffects in its contract');
    }
    if (generatedSceneLocalThreePattern.test(sceneSource)) {
      errors.push('generated recipe scene must not create local Three.js meshes, geometries, materials, points, or lines');
    }
    if (/\.controllers\.setLabel\s*\(\s*['"`]/.test(sceneSource)) {
      errors.push('generated recipe scene must call apparatus label controllers with structured label objects');
    }
    if (/free-drag/.test(resolvedRecipe.interaction || '') && resolvedRecipe.steps?.some((step) => dragStepTypes.has(step.type))) {
      if (!/\boverlapObject\s*:/.test(sceneSource)) {
        errors.push('generated free-drag recipe scene must pass overlapObject for object-level step completion');
      }
      if (!/\boverlapPadding\s*:/.test(sceneSource)) {
        errors.push('generated free-drag recipe scene must pass overlapPadding for object-level step completion');
      }
    }
    for (const step of resolvedRecipe.steps || []) {
      if (step?.id && !sceneSource.includes(step.id)) {
        errors.push(`generated recipe scene is missing recipe step id: ${step.id}`);
      }
    }
    if (isActiveClassicRecipeId(resolvedRecipe.id)) {
      if (!/from '\.\.\/\.\.\/lib\/classic-kit\/apparatus\.js';/.test(sceneSource)) {
        errors.push(`${resolvedRecipe.id} scene must import apparatus from lib/classic-kit/apparatus.js`);
      }
      if (/from '\.\.\/\.\.\/lib\/apparatus\/index\.js'/.test(sceneSource) || /from '\.\.\/\.\.\/lib\/apparatus\/presets\.js'/.test(sceneSource)) {
        errors.push(`${resolvedRecipe.id} scene must not import from legacy lib/apparatus surface`);
      }
      if (
        /\bcreateTestTubeApparatus\b/.test(sceneSource)
        || /\bcreateReagentBottleApparatus\b/.test(sceneSource)
        || /\bcreateSolidReagentJarApparatus\b/.test(sceneSource)
        || /\bcreateBeakerApparatus\b/.test(sceneSource)
        || /\bcreateErlenmeyerApparatus\b/.test(sceneSource)
        || /\bcreateDropperApparatus\b/.test(sceneSource)
        || /\bcreateGasJarApparatus\b/.test(sceneSource)
        || /\bcreateFunnelApparatus\b/.test(sceneSource)
        || /\bcreateLitmusPaperApparatus\b/.test(sceneSource)
        || /\bcreateBottleApparatus\b/.test(sceneSource)
        || /\bcreateCopperPieceApparatus\b/.test(sceneSource)
      ) {
        errors.push(`${resolvedRecipe.id} scene must not use legacy apparatus factories`);
      }
      if (/controllers\.setLabel\s*\(\{/.test(sceneSource) || /createContextualLabelPolicy\s*\(\{/.test(sceneSource)) {
        errors.push(`${resolvedRecipe.id} scene must keep learner labels out of the 3D scene`);
      }
    }
    if (resolvedRecipe.id === 'zinc-copper-hcl-compare') {
      if (!/cameraPreset:\s*"?(rack-2tube-front|classic-lab-wide)"?/.test(sceneSource)) {
        errors.push('zinc-copper comparison scene must use the classic close comparison camera');
      }
      if (!/createClassicTestTubeApparatus/.test(sceneSource)) {
        errors.push('zinc-copper comparison scene must use classic showcase test-tube apparatus');
      }
    }
    if (resolvedRecipe.id === 'hcl-nahco3-gas-release') {
      if (!/cameraPreset:\s*"?(showcase-close|single-vessel-angle)"?/.test(sceneSource)) {
        errors.push('hcl-nahco3 scene must use a close classic single-vessel camera');
      }
      if (!/createClassicTestTubeApparatus/.test(sceneSource) || !/createClassicSolidReagentJarApparatus/.test(sceneSource) || !/createClassicReagentBottleApparatus/.test(sceneSource)) {
        errors.push('hcl-nahco3 scene must use classic showcase tube, jar, and bottle apparatus');
      }
    }
    if (resolvedRecipe.id === 'halogen-halide-displacement-compare') {
      if (!/cameraPreset:\s*"?(rack-3tube-front|classic-lab-wide)"?/.test(sceneSource)) {
        errors.push('halogen-halide comparison scene must use the classic three-tube comparison camera');
      }
      if (!/createClassicTestTubeApparatus/.test(sceneSource) || !/createClassicReagentBottleApparatus/.test(sceneSource)) {
        errors.push('halogen-halide comparison scene must use classic showcase tubes and bottles');
      }
    }
    if (resolvedRecipe.id === 'moist-chlorine-bleaches-colored-paper') {
      if (!/cameraPreset:\s*"?(flask-showcase-close|showcase-close)"?/.test(sceneSource)) {
        errors.push('moist-chlorine scene must use the classic flask-showcase close camera');
      }
      if (!/createClassicErlenmeyerApparatus/.test(sceneSource) || !/createClassicMoistPaperApparatus/.test(sceneSource)) {
        errors.push('moist-chlorine scene must use classic showcase erlenmeyer and moist paper apparatus');
      }
    }
  }

  for (const effect of resolvedRecipe.effects || []) {
    const pattern = effectPatterns[effect];
    if (pattern?.test(sceneSource)) {
      errors.push(`recipe scene must use shared effect module instead of scene-local ${effect} implementation`);
    }
  }

  if (/\bfunction\s+animate\s*\([^)]*\)\s*\{[\s\S]{2500,}\brequestAnimationFrame\s*\(\s*animate\s*\)/.test(sceneSource)) {
    warnings.push('scene animate() is large; consider moving reaction progress into lib/reactions');
  }

  return { ok: errors.length === 0, errors, warnings, recipe: resolvedRecipe.id };
}

async function resolveInputs(inputArg, sceneArg) {
  if (!inputArg) {
    throw new Error('Usage: node scripts/audit-recipe-scene-contract.mjs <draft-dir|semantic-draft.json> [scene.js]');
  }

  const inputPath = path.resolve(repoRoot, inputArg);
  const stat = await fs.stat(inputPath);
  if (stat.isDirectory()) {
    const draftPath = path.join(inputPath, 'semantic-draft.json');
    const slug = path.basename(inputPath);
    const scenePath = sceneArg
      ? path.resolve(repoRoot, sceneArg)
      : path.join(inputPath, `${slug}.scene.js`);
    return { draftPath, scenePath };
  }

  const draftPath = inputPath;
  const scenePath = sceneArg
    ? path.resolve(repoRoot, sceneArg)
    : path.join(path.dirname(inputPath), `${path.basename(path.dirname(inputPath))}.scene.js`);
  return { draftPath, scenePath };
}

async function main() {
  const [inputArg, sceneArg] = process.argv.slice(2);
  const { draftPath, scenePath } = await resolveInputs(inputArg, sceneArg);
  const [draftRaw, sceneSource] = await Promise.all([
    fs.readFile(draftPath, 'utf8'),
    fs.readFile(scenePath, 'utf8'),
  ]);
  const result = await auditRecipeSceneContract({
    draft: JSON.parse(draftRaw),
    sceneSource,
  });

  console.log(JSON.stringify({
    check: 'recipe-scene-contract',
    draftPath,
    scenePath,
    ...result,
  }, null, 2));

  if (!result.ok) {
    process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
